// Pulls every public post from Substack into content/posts/ as markdown.
// Usage: npm run sync
//
// Files it writes are fully generated: anything edited by hand in them is
// replaced on the next run. Per-post decisions live in content/overrides.json.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { htmlToMarkdown } from './convert.mjs'

const SUBSTACK_URL = 'https://mcradcliffe.substack.com'
const PAGE_SIZE = 25
const GENERATED_NOTICE = '# Generated by `npm run sync`. Do not edit by hand; see README.md.'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const postsDir = join(root, 'content', 'posts')
const overrides = JSON.parse(readFileSync(join(root, 'content', 'overrides.json'), 'utf8'))

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function getJson(path, retries = 1) {
  const res = await fetch(`${SUBSTACK_URL}${path}`, {
    headers: { 'User-Agent': 'Mozilla/5.0 (blog-site content sync)', Accept: 'application/json' },
    signal: AbortSignal.timeout(30_000),
  })
  if ((res.status === 429 || res.status >= 500) && retries > 0) {
    await sleep(5_000)
    return getJson(path, retries - 1)
  }
  if (!res.ok) throw new Error(`Substack returned ${res.status} for ${path}`)
  return res.json()
}

async function listPosts() {
  const posts = []
  for (let offset = 0; ; offset += PAGE_SIZE) {
    const page = await getJson(`/api/v1/archive?sort=new&offset=${offset}&limit=${PAGE_SIZE}`)
    posts.push(...page)
    if (page.length < PAGE_SIZE) return posts
  }
}

function buildFile(post, { keepImages }) {
  const frontmatter = stringify({
    title: post.title,
    date: post.post_date,
    summary: post.subtitle || post.description || '',
    tags: (post.postTags ?? []).map((tag) => tag.name),
    source: 'substack',
    url: post.canonical_url ?? `${SUBSTACK_URL}/p/${post.slug}`,
  })
  const body = htmlToMarkdown(post.body_html, { keepImages })
  return `---\n${GENERATED_NOTICE}\n${frontmatter}---\n${body}`
}

async function syncPost(slug) {
  // The slug becomes a file name, so it must not be able to leave postsDir.
  if (!/^[a-z0-9][a-z0-9-]*$/i.test(slug)) throw new Error('Refusing unexpected slug')

  const override = overrides[slug] ?? {}
  if (override.sync === false) return 'frozen'

  const post = await getJson(`/api/v1/posts/${slug}`)
  if (!post.body_html) throw new Error('Substack returned no body')

  const file = join(postsDir, `${slug}.md`)
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : null
  const output = buildFile(post, { keepImages: override.images === true })

  if (existing === output) return 'unchanged'
  // Guards against Substack one day handing back a teaser instead of the post.
  if (existing && output.length < existing.length / 2) {
    throw new Error(
      'New version is less than half the size of the saved one, so it was not written. ' +
        'If the cut is intentional, delete the file and sync again.',
    )
  }
  writeFileSync(file, output)
  return existing ? 'updated' : 'added'
}

// A post that has left Substack is reported, never deleted: taking a post off
// the site is a deliberate act (`"hidden": true` in overrides, or delete the file).
function findOrphans(liveSlugs) {
  return readdirSync(postsDir)
    .filter((name) => name.endsWith('.md'))
    .filter((name) => /^source: substack$/m.test(readFileSync(join(postsDir, name), 'utf8')))
    .map((name) => name.replace(/\.md$/, ''))
    .filter((slug) => !liveSlugs.includes(slug))
}

async function main() {
  mkdirSync(postsDir, { recursive: true })
  const slugs = (await listPosts())
    .filter((post) => post.audience === 'everyone' && post.type === 'newsletter')
    .map((post) => post.slug)
  if (slugs.length === 0) throw new Error('Substack returned no posts; refusing to continue')

  let failures = 0
  for (const slug of slugs) {
    try {
      console.log(`${(await syncPost(slug)).padEnd(9)} ${slug}`)
    } catch (error) {
      failures += 1
      console.error(`::error::${slug}: ${error.message}`)
    }
    await sleep(500)
  }

  for (const slug of findOrphans(slugs)) {
    console.warn(`::warning::${slug} is no longer public on Substack but is still on the site`)
  }

  if (failures > 0) throw new Error(`${failures} post(s) failed to sync`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
